"""Report step: charts and a Markdown summary."""

import logging
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

logger = logging.getLogger(__name__)

SURFACE = "#fcfcfb"
TEXT_PRIMARY = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"
SERIES = "#2a78d6"
TREND = "#e34948"

plt.rcParams.update(
    {
        "figure.facecolor": SURFACE,
        "axes.facecolor": SURFACE,
        "axes.edgecolor": GRID,
        "axes.labelcolor": TEXT_SECONDARY,
        "axes.titlecolor": TEXT_PRIMARY,
        "axes.titlelocation": "left",
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.grid": True,
        "grid.color": GRID,
        "grid.linewidth": 0.8,
        "xtick.color": TEXT_SECONDARY,
        "ytick.color": TEXT_SECONDARY,
        "font.size": 10,
    }
)


def _save(fig: plt.Figure, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    logger.info("Saved %s", path)
    return path


def plot_annual_temperatures(annual: pd.DataFrame, trends: pd.DataFrame, figures_dir: Path) -> Path:
    cities = trends["city"].tolist()
    fig, axes = plt.subplots(2, 3, figsize=(12, 6.5), sharex=True)
    for ax, city in zip(axes.flat, cities, strict=True):
        data = annual[annual["city"] == city]
        ax.plot(data["year"], data["temp_mean"], color=SERIES, linewidth=2)
        slope, intercept = np.polyfit(data["year"], data["temp_mean"], deg=1)
        ax.plot(
            data["year"],
            slope * data["year"] + intercept,
            color=TREND,
            linewidth=1.5,
            linestyle="--",
        )
        ax.set_title(f"{city}  {slope * 10:+.2f} °C/decade", fontsize=11, fontweight="bold")
        ax.yaxis.set_major_formatter(lambda value, _pos: f"{value:.1f}°")
        ax.grid(axis="x", visible=False)
    fig.suptitle(
        "Annual mean temperature, 1995–2024 (solid) with linear trend (dashed)",
        x=0.01,
        ha="left",
        fontsize=13,
        fontweight="bold",
        color=TEXT_PRIMARY,
    )
    fig.text(0.01, -0.01, "Each panel uses its own y-axis scale.", color=TEXT_SECONDARY)
    fig.tight_layout()
    return _save(fig, figures_dir / "annual_temperatures.png")


def plot_warming_rates(trends: pd.DataFrame, figures_dir: Path) -> Path:
    data = trends.iloc[::-1]
    fig, ax = plt.subplots(figsize=(9, 4))
    bars = ax.barh(data["city"], data["trend_c_per_decade"], color=SERIES, height=0.6)
    ax.grid(axis="y", visible=False)
    ax.axvline(0, color=TEXT_SECONDARY, linewidth=0.8)
    for bar in bars:
        value = bar.get_width()
        # Labels always sit right of the bar end (or of zero for negative bars),
        # so they never collide with the city names on the y-axis.
        ax.text(
            max(value, 0) + 0.01,
            bar.get_y() + bar.get_height() / 2,
            f"{value:+.2f} °C",
            va="center",
            ha="left",
            color=TEXT_PRIMARY,
        )
    low = min(0, data["trend_c_per_decade"].min())
    ax.set_xlim(low * 1.5, data["trend_c_per_decade"].max() * 1.3)
    ax.set_title("Warming rate per decade, 1995–2024", fontsize=13, fontweight="bold")
    return _save(fig, figures_dir / "warming_rates.png")


def write_summary(
    trends: pd.DataFrame,
    decades: pd.DataFrame,
    issues: list[str],
    rows: int,
    reports_dir: Path,
) -> Path:
    trend_rows = "\n".join(
        f"| {r.city} | {r.country} | {r.trend_c_per_decade:+.2f} |" for r in trends.itertuples()
    )
    decade_rows = "\n".join(
        f"| {r.city} | {r.temp_before:.2f} °C | {r.temp_after:.2f} °C | {r.change_c:+.2f} °C "
        f"| {r.rain_change_pct:+.0%} |"
        for r in decades.itertuples()
    )
    quality = "No issues found." if not issues else "\n".join(f"- {i}" for i in issues)
    fastest = trends.iloc[0]
    slowest = trends.iloc[-1]

    content = f"""# Analysis summary

> Auto-generated by `python -m climate.pipeline`. Do not edit by hand.

**Rows analyzed:** {rows:,} daily observations · **Cities:** {len(trends)} · **Period:** 1995–2024

## Key findings

- **{(trends["trend_c_per_decade"] > 0).sum()} of {len(trends)} capitals warmed** over the period.
- **Fastest warming:** {fastest.city} at **{fastest.trend_c_per_decade:+.2f} °C per decade**.
- **Slowest warming:** {slowest.city} at **{slowest.trend_c_per_decade:+.2f} °C per decade**.

## Warming trend (linear regression on annual means)

| City | Country | °C per decade |
|---|---|---:|
{trend_rows}

## 1995–2004 vs 2015–2024

| City | 1995–2004 | 2015–2024 | Change | Rainfall change |
|---|---:|---:|---:|---:|
{decade_rows}

## Data quality

{quality}

## Charts

![Annual temperatures](figures/annual_temperatures.png)
![Warming rates](figures/warming_rates.png)
"""
    path = reports_dir / "summary.md"
    path.write_text(content, encoding="utf-8")
    logger.info("Saved %s", path)
    return path
